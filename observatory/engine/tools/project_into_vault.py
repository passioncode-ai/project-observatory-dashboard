#!/usr/bin/env python3
"""Write the read-only registry projection into the narrative wiki.

The registry is canonical here. The vault keeps a generated copy so Obsidian
links and the wiki-* skills keep resolving. Every file carries a header saying
it is generated, because a projection nobody can tell from a source is the
second source of truth this split exists to prevent.
"""
from __future__ import annotations
import json, sys, pathlib
from datetime import datetime, timezone
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import atomic
import paths

HEADER = {
    "_generated": True,
    "_generated_by": "project-observatory/tools/project_into_vault.py",
    "_canonical_source": paths.REGISTRY.as_uri(),
    "_do_not_edit": "Edits here are overwritten on the next projection. Change the registry instead.",
}
#: Registry documents the mirror deliberately does NOT carry, with the reason.
#: Empty today, and that is the point: the set of files is DERIVED from the
#: registry rather than listed here. It was a literal of seven names, and by
#: 2026-09-07 the registry held ten — `domain-liveness.json`,
#: `findings.json` and `stale-remotes.json` were absent from the wiki and
#: nothing said so. `findings.json` is the one that matters most: the wiki is
#: where the operator's narrative memory lives, and "what needs a person" was
#: the document missing from it.
#:
#: Same class as `purge_projections`' hardcoded pair of indexes, `OWNED_ORGS`,
#: and `scan_github`'s output directory. A document added to the registry now
#: appears in the mirror by default, and excluding one takes a sentence.
NOT_MIRRORED: dict[str, str] = {}
#: Readable pages written beside the mirrored JSON, each from one registry document (OBS-317):
#: the wiki links `[[inventory/agents]]`, a note Obsidian and `audit_vault_links.py` resolve to
#: `inventory/agents.md`, and a JSON file is not a note.
PAGES = {"agents.json": "agents.md"}


def _cell(value) -> str:
    """One table cell: a pipe escaped and a line break folded, so no value can end the row."""
    text = " ".join(str(value).split()) if value not in (None, "") else ""
    return text.replace("|", "\\|") or "none"


def _holder(sup: dict) -> str:
    sup = sup if isinstance(sup, dict) else {}
    name = next((sup[k] for k in ("label", "unit", "task") if isinstance(sup.get(k), str) and sup[k]), None)
    parts = [str(sup.get("manager") or "nobody")] + ([f"`{name}`"] if name else [])
    return " ".join(parts) + (f" ({sup['state']})" if sup.get("state") else "")


def _contract(man: dict) -> str:
    man = man if isinstance(man, dict) else {}
    if man.get("state") != "pinned":
        return f"manifest {man.get('state') or 'absent'}"
    pin = str(man.get("contract_version") or "unstated")
    return pin + (f" ({man['provider_id']})" if man.get("provider_id") else "")


def agents_markdown(doc: dict) -> str:
    """`inventory/agents.md` from `registry/agents.json`: one row per installed service, ordered by its
    key so the page changes only when the estate does. Only fields the JSON already carries, and none
    of a descriptor's paths: no plist, no data folder, no token file."""
    rows = sorted((a for a in doc.get("agents") or [] if isinstance(a, dict)),
                  key=lambda a: (str(a.get("service_id") or ""), str(a.get("instance") or ""), str(a.get("id"))))
    lines = ["# Installed agents", "",
             "Generated by project-observatory/tools/project_into_vault.py from `inventory/agents.json` "
             f"(registry updated {doc.get('updated_on') or 'unknown'}, scanned {doc.get('scanned_on') or 'unknown'}"
             f"{', stale' if doc.get('stale') else ''}). Do not edit: the next projection overwrites this page; "
             "change the service's descriptor instead.", ""]
    if not rows:
        lines.append("No agent service is installed: no fabric-service/0.1 descriptor was found.")
    else:
        lines += ["| Service key | Product | Version | Where it answers | Contract pin | Held by | MCP declarations |",
                  "|---|---|---|---|---|---|---|"]
        for a in rows:
            key = f"{a.get('service_id') or a.get('id')}.{a.get('instance') or 'default'}"
            man = a.get("manifest") if isinstance(a.get("manifest"), dict) else {}
            version = f"revision {man['provider_revision']}" if man.get("provider_revision") is not None else "unstated"
            where = a.get("origin") or (f"{a.get('host')}:{a.get('port')}" if a.get("host") else None)
            where = f"{where or 'no origin'} ({a.get('placement') or 'unknown'})"
            mcp = a.get("mcp_declarations")
            mcp_text = "not read" if mcp is None else ", ".join(f"`{m}`" for m in sorted(mcp)) or "none"
            lines.append("| " + " | ".join([f"`{_cell(key)}`", _cell(a.get("name") or a.get("service_id")),
                                            _cell(version), _cell(where), _cell(_contract(man)),
                                            _holder(a.get("supervisor")), mcp_text]) + " |")
    removed = [r for r in doc.get("removed") or [] if isinstance(r, str)]
    if removed:
        lines += ["", "Removed since the previous scan: " + ", ".join(f"`{_cell(r)}`" for r in sorted(removed)) + "."]
    degraded = [d for d in doc.get("degraded") or [] if isinstance(d, dict)]
    if degraded:
        lines += ["", "Not fully read:"] + [f"- {_cell(d.get('source'))}: {_cell(d.get('reason'))}" for d in degraded]
    return "\n".join(lines) + "\n"


def main() -> int:
    dest = paths.VAULT_PROJECTION
    if not dest.parent.is_dir():
        print(f"vault not found at {paths.VAULT} — set OBSERVATORY_VAULT", file=sys.stderr)
        return 1
    dest.mkdir(parents=True, exist_ok=True)
    written, skipped, pages = 0, [], []
    for src in sorted(paths.REGISTRY.glob("*.json")):
        name = src.name
        if name in NOT_MIRRORED:
            skipped.append({"file": name, "why": NOT_MIRRORED[name]})
            continue
        try:
            doc = json.loads(src.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            # NAMED, not skipped in silence: a registry document this cannot read
            # is a hole in the mirror, and the wiki skills read the mirror.
            skipped.append({"file": name, "why": f"unreadable: {type(exc).__name__}"})
            print(f"skip (unreadable): {name}", file=sys.stderr)
            continue
        if not isinstance(doc, dict):
            skipped.append({"file": name, "why": "not a JSON object, so no header "
                                                 "could be merged into it"})
            print(f"skip (not an object): {name}", file=sys.stderr)
            continue
        # ATOMIC, because the destination is ANOTHER repository that the wiki
        # skills read. A direct `write_text` that dies mid-write leaves
        # truncated JSON there, and `atomic.write_json` exists in this project
        # for exactly that.
        atomic.write_json(dest / name, {**HEADER, **doc})
        written += 1
        if name in PAGES:
            atomic.write_text(dest / PAGES[name], agents_markdown(doc))
            pages.append(PAGES[name])
    snap_src, snap_dest = paths.REGISTRY / "snapshots", dest / "snapshots"
    if snap_src.is_dir():
        snap_dest.mkdir(exist_ok=True)
        for f in sorted(snap_src.glob("*.json")):
            (snap_dest / f.name).write_text(f.read_text(encoding="utf-8"), encoding="utf-8")
            written += 1
    print(f"projected {written} files into {dest}" + (f", and the page(s) {', '.join(pages)}" if pages else ""))
    for sk in skipped:
        print(f"  not mirrored: {sk['file']} — {sk['why']}")
    # The run as a fact. A mirror missing three of ten documents said so on
    # stdout and nowhere else.
    try:
        paths.SCRATCH.mkdir(parents=True, exist_ok=True)
        atomic.write_json(paths.SCRATCH / "projection.json", {
            "ran_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "written": written, "skipped": skipped, "pages": pages,
            "registry_documents": len(list(paths.REGISTRY.glob("*.json"))),
            "destination": str(dest)})
    except OSError as exc:
        print(f"could not write the projection report: {exc}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    import configuration
    if (True) and not configuration.enabled("wiki_projection", "features"):
        print("Not configured: enable features.wiki_projection explicitly")
        raise SystemExit(0)

    raise SystemExit(main())
