def branch_name_reason(repo: str, name) -> str:
    if not isinstance(name, str) or not name or name.startswith("-"):
        return "branch name is invalid"
    checked = git(repo, "check-ref-format", "--branch", name)
    # --branch can expand shortcuts such as @{-1}; plans must name the literal branch.
    if checked.returncode or checked.stdout.strip() != name:
        return "branch name is invalid or not literal"
    return ""


def still_safe_branch(a: dict, expected: str | None = None) -> str:
    """Prove eligibility for a fixed tip and refuse unreadable checkout state."""
    repo, name, default = a["repo"], a["target"], a.get("default_branch")
    why = branch_name_reason(repo, name)
    if why:
        return why
    symbolic = git(repo, "symbolic-ref", "--quiet", "refs/heads/" + name)
    if symbolic.returncode == 0:
        return "symbolic branch refs are not cleanup targets"
    if symbolic.returncode != 1:
        return "branch ref type could not be read"
    tip = git(repo, "rev-parse", "--verify", "refs/heads/" + name)
    if tip.returncode or not tip.stdout.strip():
        return "branch no longer exists or could not be read"
    sha = tip.stdout.strip()
    if expected is not None and sha != expected:
        return "branch tip changed since its cleanup proof"
    worktrees = git(repo, "worktree", "list", "--porcelain")
    if worktrees.returncode or not worktrees.stdout.startswith("worktree "):
        return "worktree attachments could not be read"
    held = {line.split(" ", 1)[1] for line in worktrees.stdout.splitlines() if line.startswith("branch ")}
    if "refs/heads/" + name in held:
        return "branch is checked out in a worktree now"
    if a["class"] == "branch-merged":
        ahead = git(repo, "rev-list", "--count", f"{default}..{sha}")
        if ahead.returncode:
            return "branch merge proof could not be read"
        if ahead.stdout.strip() != "0":
            cherry = git(repo, "cherry", default, sha)
            if cherry.returncode or not cherry.stdout or not all(c.startswith("-") for c in cherry.stdout.splitlines()):
                return "branch has commits the default branch lacks now"
    if a["class"] == "branch-pushed":
        up = git(repo, "rev-parse", "--abbrev-ref", name + "@{upstream}")
        if up.returncode or not up.stdout.strip():
            return "branch upstream could not be read"
        # `branch.X.remote=.` makes a local branch the upstream: identical to it proves no copy
        # exists anywhere else, least of all when the upstream is the branch itself.
        remote = git(repo, "config", "--get", f"branch.{name}.remote")
        if remote.returncode or remote.stdout.strip() in ("", "."):
            return "branch upstream is local, not a remote copy"
        full = git(repo, "rev-parse", "--symbolic-full-name", name + "@{upstream}")
        if full.returncode or not full.stdout.strip().startswith("refs/remotes/"):
            return "branch upstream is not a remote-tracking ref"
        ahead = git(repo, "rev-list", "--count", f"{up.stdout.strip()}..{sha}")
        if ahead.returncode or ahead.stdout.strip() != "0":
            return "branch is no longer identical to its upstream"
    return ""


def busy_now(path: str) -> bool:
    """Preliminary cached refusal; unknown coverage never grants removal."""
    import holders
    global _LISTING
    # Current process observations cannot prove a path unused. Cache explicit
    # non-observation without collecting hints that cannot alter this refusal.
    taken, listing = _LISTING
    if listing is None or time.monotonic() - taken > RECHECK_FRESH_SECONDS:
        listing = holders.Holders.take(60, collect_hints=False)
        _LISTING = (time.monotonic(), listing)
    return listing.busy(path)


#: Maximum age of the preliminary refusal cache; never the final removal proof.
RECHECK_FRESH_SECONDS = 20
_LISTING: tuple = (0.0, None)


def ignored_keepers(target: str, artifacts: set[str]) -> list[str]:
    """Ignored files in a worktree that are NOT build output (`.env.local`, a local database,
    `.wrangler/state`): `git worktree remove` deletes them with the worktree, and they exist
    nowhere else. A worktree holding any is not "clean" for this tier."""
    out = git(target, "status", "--porcelain", "--ignored=matching", "--untracked-files=normal", "-z")
    if out.returncode:
        return ["(git status could not be read)"]
    artifacts = set(artifact_names({"artifact_dirs": artifacts}))
    keep = []
    for entry in out.stdout.split("\0"):
        if entry.startswith("!! "):
            rel = entry[3:].rstrip("/")
            if (".wrangler" in rel.split("/") or not any(part in artifacts for part in rel.split("/"))
                    or protected_tree_reason(os.path.join(target, rel))):
                keep.append(rel)
    return keep


def index_visibility_reason(target: str) -> str:
    """Status/diff can conceal content behind assume-unchanged or skip-worktree."""
    try:
        result = git(target, "ls-files", "-v", "-z")
        if result.returncode:
            return "index flags could not be read; nothing removed"
        rows = result.stdout.split("\0")
        if any(row and (not row.startswith("H ") or len(row) <= 2) for row in rows):
            return "index has hidden or unsupported entries; nothing removed"
        return ""
    except (OSError, subprocess.SubprocessError, UnicodeError):
        return "index flags could not be read; nothing removed"


def archive_head_ref(repo: str, head: str) -> tuple[str, str]:
    """Keep a detached HEAD reachable under `refs/heads/archive/wt-<sha8>`: (ref, refusal)."""
    name = f"archive/wt-{head[:8]}"
    ref = "refs/heads/" + name
    # A symbolic ref here would keep the commit only while its referent does: not retention.
    symbolic = git(repo, "symbolic-ref", "--quiet", ref)
    if symbolic.returncode != 1:
        return ref, ("detached HEAD archive ref is symbolic; nothing removed" if symbolic.returncode == 0
                     else "detached HEAD archive ref could not be read; nothing removed")
    existing = git(repo, "show-ref", "--verify", "--quiet", ref)
    if existing.returncode == 0:
        resolved = git(repo, "rev-parse", "--verify", ref)
        if resolved.returncode or resolved.stdout.strip() != head:
            return ref, "detached HEAD archive ref conflicts; nothing removed"
    elif existing.returncode == 1:
        made = git(repo, "branch", name, head)
        if made.returncode:
            return ref, "detached HEAD archive ref could not be created; nothing removed"
    else:
        return ref, "detached HEAD archive ref could not be read; nothing removed"
    return ref, ""


def retain_missing_head(repo: str, target: str, head: str | None) -> tuple[str, str]:
    """Before a missing worktree's registration goes, keep its HEAD reachable: (ref, refusal).

    The registration is the only thing that still names a detached worktree's commits; once it
    is removed they are unreachable and `gc` deletes them. Its current record must still carry
    the HEAD the survey saw; a branch HEAD is kept by its branch, a detached one by an archive
    ref, the same one a removed clean or dirty worktree gets. Unknown, locked or changed refuses.
    """
    try:
        if not head:
            return "", "HEAD of the missing worktree is unknown; nothing pruned"
        listed = git(repo, "worktree", "list", "--porcelain")
        if listed.returncode or not listed.stdout.startswith("worktree "):
            return "", "worktree registrations could not be read; nothing pruned"
        record = None
        for block in listed.stdout.split("\n\n"):
            fields = {}
            for line in block.splitlines():
                key, _, value = line.partition(" ")
                fields[key] = value
            if fields.get("worktree") == target:
                record = fields
        if record is None:
            return "", "the registration is gone already; nothing pruned"
        if "locked" in record:
            return "", "the registration is locked; nothing pruned"
        if record.get("HEAD") != head:
            return "", "the worktree's HEAD changed since the survey; nothing pruned"
        if git(repo, "cat-file", "-e", head + "^{commit}").returncode:
            return "", "the worktree's HEAD commit could not be read; nothing pruned"
        if record.get("branch", "").startswith("refs/heads/"):
            ref = record["branch"]
        elif "detached" in record:
            ref, why = archive_head_ref(repo, head)
            if why:
                return ref, why.replace("nothing removed", "nothing pruned")
        else:
            return "", "the worktree's HEAD attachment could not be read; nothing pruned"
        retained = git(repo, "rev-parse", "--verify", ref)
        if retained.returncode or retained.stdout.strip() != head:
            return ref, "HEAD retention could not be verified; nothing pruned"
        if git(repo, "symbolic-ref", "--quiet", ref).returncode != 1:
            return ref, "the ref that would keep HEAD is symbolic; nothing pruned"
        return ref, ""
    except (OSError, subprocess.SubprocessError, UnicodeError):
        return "", "HEAD retention could not be read; nothing pruned"


def missing_admin_entry(repo: str, target: str, head: str) -> tuple[pathlib.Path | None, str]:
    """The one `.git/worktrees/<name>` entry whose `gitdir` points at `target`: (entry, refusal).

    Matched by the path the entry itself records, never by a name, and its HEAD file must
    still be the HEAD that was kept. A locked, ambiguous or unreadable entry refuses."""
    common = git(repo, "rev-parse", "--git-common-dir")      # relative to `repo` before Git 2.31
    if common.returncode or not common.stdout.strip():
        return None, "the repository's git directory could not be read; nothing pruned"
    root = pathlib.Path(repo, common.stdout.strip()) / "worktrees"
    want = os.path.normpath(target)
    found = []
    for entry in root.iterdir():
        gitdir = (entry / "gitdir").read_text(encoding="utf-8").strip() if (entry / "gitdir").is_file() else ""
        if gitdir and os.path.isabs(gitdir) and os.path.basename(gitdir) == ".git" \
                and os.path.normpath(os.path.dirname(gitdir)) == want:
            found.append(entry)
    if len(found) != 1:
        return None, "the registration's entry could not be identified; nothing pruned"
    entry = found[0]
    if (entry / "locked").exists() or os.path.islink(entry) or not entry.is_dir():
        return None, "the registration's entry is locked or not a plain folder; nothing pruned"
    recorded = (entry / "HEAD").read_text(encoding="utf-8").strip()
    if recorded.startswith("ref: "):
        tip = git(repo, "rev-parse", "--verify", recorded[5:])
        recorded = tip.stdout.strip() if tip.returncode == 0 else ""
    if recorded != head:
        return None, "the worktree's HEAD changed since it was kept; nothing pruned"
    return entry, ""


def retain_worktree_head(repo: str, target: str, head: str) -> str:
    """Prove current HEAD remains reachable without trusting the survey's branch."""
    try:
        if not head:
            return "HEAD could not be read; nothing removed"
        symbolic = git(target, "symbolic-ref", "--quiet", "HEAD")
        if symbolic.returncode == 0:
            ref = symbolic.stdout.strip()
            if not ref.startswith("refs/heads/"):
                return "HEAD branch could not be verified; nothing removed"
        elif symbolic.returncode == 1:
            ref, why = archive_head_ref(repo, head)
            if why:
                return why
        else:
            return "HEAD attachment could not be read; nothing removed"
        retained = git(repo, "rev-parse", "--verify", ref)
        current = git(target, "rev-parse", "--verify", "HEAD")
        if (retained.returncode or current.returncode or retained.stdout.strip() != head
                or current.stdout.strip() != head):
            return "HEAD retention changed or could not be verified; nothing removed"
        return ""
    except (OSError, subprocess.SubprocessError, UnicodeError):
        return "HEAD retention could not be read; nothing removed"


def act(a: dict, archive: pathlib.Path) -> dict:
    cls, repo, target = a["class"], a.get("repo"), a["target"]
    rec = {"at": now(), "class": cls, "tier": a["tier"], "target": target, **({"repository": a["repository"]} if "repository" in a else {})}
    if cls in ("branch-merged", "branch-pushed", "branch-unique"):
        why = branch_name_reason(repo, target)
        if not why and cls in ("branch-merged", "branch-unique"):
            why = branch_name_reason(repo, a.get("default_branch"))
        if why:
            return {**rec, "result": "skipped", "reason": why}
        tip = git(repo, "rev-parse", "--verify", "refs/heads/" + target)
        if tip.returncode or not tip.stdout.strip():
            return {**rec, "result": "skipped", "reason": "branch tip could not be read"}
        sha = tip.stdout.strip()
        rec["sha"] = sha
        why = still_safe_branch(a, sha)
        if why:
            return {**rec, "result": "skipped", "reason": why}
        if cls == "branch-unique":
            archive.mkdir(parents=True, exist_ok=True, mode=0o700)
            folder = pathlib.Path(tempfile.mkdtemp(prefix="branch-" + sha[:8] + "-", dir=archive))  # paths-check: allow - durable recovery archive under the caller's redirected archive root, never temporary test state
            bundle = folder / "branch.bundle"
            rec["archive"] = str(bundle)
            made = git(repo, "bundle", "create", str(bundle), "refs/heads/" + target, "^" + a["default_branch"])
            if made.returncode or git(repo, "bundle", "verify", str(bundle)).returncode:
                return {**rec, "result": "failed", "reason": "bundle could not be written and verified; nothing deleted"}
            os.chmod(bundle, 0o600)
            heads = git(repo, "bundle", "list-heads", str(bundle))
            if heads.returncode or heads.stdout.splitlines() != [sha + " refs/heads/" + target]:
                return {**rec, "result": "failed", "reason": "bundle does not contain the proven branch tip; nothing deleted"}
        why = still_safe_branch(a, sha)
        if why:
            return {**rec, "result": "skipped", "reason": why}
        # Expected-old-value deletion cannot remove a newer tip. Worktree attachment
        # is checked above; an unrelated checkout still has a final check/use race.
        # A late symbolic-ref conversion must never redirect deletion to its referent.
        done = git(repo, "update-ref", "-d", "--no-deref", "refs/heads/" + target, sha)
        return {**rec, "result": "removed" if done.returncode == 0 else "failed",
                **({"reason": "branch changed or could not be deleted; nothing deleted"} if done.returncode else {})}
    if cls == "worktree-missing":
        presence = worktree_presence(target)
        if presence == "present":
            return {**rec, "result": "skipped", "reason": "the directory exists again"}
        if presence != "absent":
            return {**rec, "result": "skipped", "reason_code": "presence-unknown",
                    "reason": "the directory could not be proven absent (an unmounted drive, a renamed "
                              "or unreadable parent folder); nothing pruned"}
        rec["head"] = a.get("head")
        ref, why = retain_missing_head(repo, target, a.get("head"))
        if why:
            return {**rec, "result": "skipped", "reason": why}
        rec["retained_ref"] = ref
        # Only the administrative entry moves, never a working directory and never a
        # repository-wide `git worktree prune` (which also drops the records of worktrees on an
        # unplugged drive). The entry is renamed aside inside the repository, index and reflog
        # kept: a directory that reappears after this check loses nothing, and moving the entry
        # back (then `git worktree repair`) restores the registration.
        detail = {"scope": "one-registration", "registration_changes": None}
        try:
            admin, why = missing_admin_entry(repo, target, a.get("head"))
            if why:
                return {**rec, "result": "skipped", "reason": why}
            if worktree_presence(target) != "absent":
                return {**rec, "result": "skipped", "reason": "the directory reappeared; nothing pruned"}
            retired = admin.parent.parent / "worktrees-retired"
            retired.mkdir(mode=0o700, exist_ok=True)
            dest = retired / f"{admin.name}-{rec['head'][:8]}-{int(time.time())}"
            os.rename(admin, dest)
        except (OSError, subprocess.SubprocessError, UnicodeError):
            return {**rec, **detail, "result": "failed", "effect": "unknown",
                    "reason_code": "registration-prune-incomplete",
                    "reason": "registration removal did not complete; inspect current registrations before retrying"}
        rec["retired_entry"] = "worktrees-retired/" + dest.name
        return {**rec, **detail, "result": "pruned", "exit_code": 0}
    if cls in ("worktree-clean", "worktree-dirty"):
        if busy_now(target):
            unknown = _LISTING[1] is not None and not getattr(_LISTING[1], "known", True)
            return {**rec, "result": "skipped",
                    "reason": "holders could not be checked; nothing removed" if unknown
                    else "a process works inside it now"}
        why = index_visibility_reason(target)
        if why:
            return {**rec, "result": "skipped", "reason": why}
        status = git(target, "status", "--porcelain", "--untracked-files=normal")
        if status.returncode:
            return {**rec, "result": "skipped", "reason": "git status could not be read"}
        if cls == "worktree-clean" and status.stdout.strip():
            return {**rec, "result": "skipped", "reason": "it has uncommitted changes now"}
        if cls == "worktree-clean":
            keepers = ignored_keepers(target, set(a.get("artifacts") or []))
            if keepers:
                return {**rec, "result": "skipped",
                        "reason": f"it holds {len(keepers)} ignored file(s) that are not build output, "
                                  f"e.g. {keepers[0][:60]}"}
        if cls == "worktree-dirty" and ignored_keepers(target, set()):
            return {**rec, "result": "skipped", "reason": "ignored files are outside the manual archive; "
                    "preserve or move them first, then rerun full cleanup --apply --include manual"}
        rec["head"] = git(target, "rev-parse", "HEAD").stdout.strip()
        if cls == "worktree-dirty":
            # Capture and verify before forced removal; an unreadable or changing
            # source is preserved, even if a partial recovery directory was written.
            deadline = min(time.monotonic() + ARCHIVE_SECONDS, a.get("_deadline") or float("inf"))
            try:
                if not rec["head"]:
                    raise ArchiveRefused("HEAD could not be resolved")
                archive_time_left(deadline)
                archive.mkdir(parents=True, exist_ok=True, mode=0o700)
                # A failed attempt keeps a named partial archive; retries never overwrite it.
                dest = pathlib.Path(tempfile.mkdtemp(prefix=pathlib.Path(target).name + "-" + rec["head"][:8] + "-", dir=archive))  # paths-check: allow - durable recovery archive under the caller's redirected archive root, retained after exit
                rec["archive"] = str(dest)
                patch, staged, manifest = archive_manual(target, dest, status.stdout, deadline)
            except (ArchiveRefused, OSError, subprocess.SubprocessError, tarfile.TarError, ValueError) as exc:
                reason = str(exc) if isinstance(exc, ArchiveRefused) else f"manual archive verification failed ({type(exc).__name__})"
                return {**rec, "result": "failed", "reason": (reason + "; nothing removed")[:200]}
        # An archive can take time; an ignored file appearing meanwhile must not
        # be lost to the force removal either. No ignored file is in this archive.
        if cls == "worktree-dirty" and ignored_keepers(target, set()):
            return {**rec, "result": "skipped", "reason": "ignored files appeared during archiving; "
                    "preserve or move them first, then rerun full cleanup --apply --include manual"}
        if cls == "worktree-dirty":
            try:
                revalidate_manual(target, dest, rec["head"], status.stdout, patch, staged, manifest, deadline)
                if ignored_keepers(target, set()):
                    raise ArchiveRefused("ignored files appeared during archive verification")
                archive_time_left(deadline)
            except (ArchiveRefused, OSError, subprocess.SubprocessError, tarfile.TarError, ValueError) as exc:
                reason = str(exc) if isinstance(exc, ArchiveRefused) else f"manual archive recheck failed ({type(exc).__name__})"
                return {**rec, "result": "failed", "reason": (reason + "; nothing removed")[:200]}
        why = index_visibility_reason(target) or retain_worktree_head(repo, target, rec["head"])
        if why:
            return {**rec, "result": "skipped", "reason": why}
        # Do not let the preliminary cache or time spent verifying an archive
        # grant deletion. This shared target probe is the final external check.
        end = deadline if cls == "worktree-dirty" else a.get("_deadline")
        left = min(5.0, end - time.monotonic()) if end is not None else 5.0
        if left <= 0:
            return {**rec, "result": "skipped", "reason": "holder recheck budget exhausted; nothing removed"}
        held = fresh_busy(target, left)
        if held is not False:
            return {**rec, "result": "skipped", "reason": "worktree is held or holder coverage is unknown; nothing removed"}
        args = ["worktree", "remove", target] + (["--force", "--force"] if cls == "worktree-dirty" else [])
        done = git(repo, *args)
        return {**rec, "result": "removed" if done.returncode == 0 else "failed",
                **({"reason": done.stderr.strip()[:200]} if done.returncode else {})}
    if cls == "build-artifacts":
        # Only disk_guard carries the action-time eligibility/identity contract.
        # A stale legacy plan cannot prove tracked/ignored/idle state here.
        return {**rec, "result": "skipped", "reason": "legacy artifact action needs a fresh eligibility check; "
                "run full disk-guard to replan build output"}
    return {**rec, "result": "skipped", "reason": "unknown class"}


def journal(rows: list[dict]) -> None:
    log = paths.STATE / "logs" / "cleanup.jsonl"
    log.parent.mkdir(parents=True, exist_ok=True)
    with open(log, "a", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    os.chmod(log, 0o600)


def under_pressure(cfg: dict, level: str | None) -> dict:
    """The auto tier's thresholds at a disk pressure (`cleanup.json` → `pressure`).

    Only the tier that loses nothing moves: a merged or pushed branch, a clean worktree whose
    branch stays, ignored build output. A clean worktree nobody has worked in for a day is
    still a full checkout with its own dependencies — on 2026-10-11 thirteen of them sat on a
    disk that ran out — and removing it keeps its branch. The manual tier, the only copy of
    somebody's work, never moves with pressure."""
    lowered = (cfg.get("pressure") or {}).get(level or "") or {}
    if not lowered:
        return cfg
    auto = dict(cfg.get("auto") or {})
    mine = set(cfg.get("_own_auto") or [])
    for key, value in lowered.items():
        if key in auto and key not in mine and isinstance(value, (int, float)):
            auto[key] = min(auto[key], value)
    return {**cfg, "auto": auto}


def main(argv: list[str]) -> int:
    """Plan, or act on the auto tier (and the manual one when asked), under the cleanup lock.

    `--level L` lowers the auto tier's thresholds by disk pressure; `--deadline-seconds N`
    stops between actions before N seconds; every action is journalled as it happens, so a
    run stopped from outside keeps its undo record; `--json` prints one summary line."""
    import cleanup_lock
    level = argv[argv.index("--level") + 1] if "--level" in argv[:-1] else None
    deadline = None
    if "--deadline-seconds" in argv[:-1]:
        try:
            deadline = time.monotonic() + float(argv[argv.index("--deadline-seconds") + 1])
        except ValueError:
            deadline = None
    as_json = "--json" in argv

    def say(summary: dict, text: str, code: int = 0) -> int:
        print(json.dumps(summary) if as_json else text)
        return code

    with cleanup_lock.held() as mine:
        if not mine:
            return say({"result": "busy"}, "cleanup: another cleanup is running; nothing done")
        cfg = under_pressure(load_config(), level)
        import holders
        started = time.monotonic()
        # The current inventory can only refuse path actions. Do not spend the
        # plan budget collecting a machine-wide process table that cannot admit one.
        # The unknown snapshot preserves existing planning/refusal semantics.
        busy = holders.Holders.take(collect_hints=False)
        plan = build_plan(cfg, busy, artifacts="--git-only" not in argv)
        plan["level"] = level or "normal"
        plan["plan_seconds"] = round(time.monotonic() - started, 1)
        out = paths.SCRATCH / "cleanup-plan.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_suffix(".tmp")
        tmp.write_text(json.dumps(plan, indent=1, ensure_ascii=False), encoding="utf-8")
        os.chmod(tmp, 0o600)
        os.replace(tmp, out)
        counts = ", ".join(f"{k} {v}" for k, v in plan["counts"].items() if v) or "nothing"
        held_back = plan.get("carried")
        # In the JSON summary too: under `--json` the line goes to stderr, and the disk guard keeps
        # only the summary, so this is how the count reaches its report and journal.
        held = {"carried": held_back} if held_back else {}
        if held_back:
            # Said on every path, so a run that removes nothing does not read as "nothing to do".
            print(f"cleanup: {held_back['checkouts']} checkouts carried from {held_back['measured_at']}; "
                  "their auto actions wait for a fresh pass", file=sys.stderr if as_json else sys.stdout)
        if "--auto" in argv and not plan["auto_enabled"]:
            return say({"result": "plan-only", "counts": plan["counts"], **held},
                       f"cleanup: plan only (features.auto_cleanup is off) — {counts}")
        if "--auto" not in argv and "--apply" not in argv:
            return say({"result": "plan-only", "counts": plan["counts"], **held},
                       f"cleanup plan{' at ' + level if level else ''}: {counts}. Nothing removed; `--apply` removes "
                       f"the auto tier, `--apply --include manual` also archives and removes the manual tier.")
        tiers = {"auto"} | ({"manual"} if "--apply" in argv and "manual" in argv else set())
        chosen = [a for a in plan["actions"] if a["tier"] in tiers][: int(cfg.get("max_actions_per_run", 200))]
        archive = configuration.home() / "archive" / "cleanup" / datetime.now(timezone.utc).strftime("%Y-%m-%d")
        rows, stopped = [], 0
        mode = "auto" if "--auto" in argv else "manual"
        for n, a in enumerate(chosen):
            if deadline is not None and time.monotonic() > deadline:
                stopped = len(chosen) - n
                break
            try:
                row = act({**a, "_deadline": deadline}, archive)
            except (OSError, subprocess.SubprocessError) as exc:
                row = {"at": now(), "class": a["class"], "target": a["target"], "result": "failed",
                       "reason": f"{type(exc).__name__}: {exc}"[:200]}
            row = {**row, "mode": mode, **({"level": level} if level else {})}
            rows.append(row)
            journal([row])                   # as it happens: the sha of a deleted branch is its undo
        done = sum(1 for r in rows if r["result"] in ("removed", "pruned"))
        skipped = sum(1 for r in rows if r["result"] == "skipped")
        failed = sum(1 for r in rows if r["result"] == "failed")
        freed = sum(r.get("kb") or 0 for r in rows) / 1048576
        summary = {"result": "ran", "removed": done, "skipped": skipped, "failed": failed,
                   "stopped": stopped, "level": level or "normal", "plan_seconds": plan["plan_seconds"], **held}
        text = (f"cleanup: {done} removed, {skipped} skipped on re-check, {failed} failed"
                + (f"; {freed:.1f} GB of build output freed" if freed else "")
                + (f"; {stopped} left for the next run (deadline)" if stopped else ""))
        return say(summary, text, 1 if failed and not as_json else 0)

if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
